class HybridRow(dict):
    """Dict-style row with support for row[0]."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def hybrid_row(cursor):
    if cursor.description is None:
        return tuple_row(cursor)

    names = [column.name for column in cursor.description]

    def make_row(values):
        return HybridRow(zip(names, values))

    return make_row



@contextmanager
def get_db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL environment variable is not configured.")
    connection = psycopg.connect(DATABASE_URL, row_factory=hybrid_row)
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_db():
    with get_db() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'user',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                full_name TEXT
            )
        """)
        db.execute("""
            CREATE TABLE IF NOT EXISTS audit_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id),
                activity TEXT NOT NULL,
                filename TEXT,
                risk_level TEXT,
                risk_score INTEGER,
                result TEXT,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        db.execute("""
            CREATE TABLE IF NOT EXISTS login_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id),
                logged_in_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        # Keep identity sequences in sync with IDs imported from SQLite.
        for table in ("users", "audit_logs", "login_events"):
            db.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"GREATEST(COALESCE((SELECT MAX(id) FROM {table}), 1), 1), "
                f"EXISTS (SELECT 1 FROM {table}))"
            )


init_db()


